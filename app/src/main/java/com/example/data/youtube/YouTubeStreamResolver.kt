package com.example.data.youtube

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.AudioStream
import org.schabi.newpipe.extractor.stream.VideoStream
import com.github.libretube.api.obj.PipedStream
import com.github.libretube.api.obj.Streams
import com.github.libretube.player.manifest.SabrManifest
import androidx.annotation.OptIn
import androidx.media3.common.util.UnstableApi
import java.util.Locale

/** Resolves a YouTube video to a video-only stream plus an explicitly Latin-American Spanish audio track. */
data class ResolvedYouTubeStream(
    val videoUrl: String,
    val audioUrl: String,
    val audioLanguage: String,
    val hasSpanishAudio: Boolean,
    val spanishSubtitleUrl: String?,
    val spanishSubtitleMimeType: String?,
    val videoHeight: Int,
    val durationSeconds: Long,
    val sabrManifest: SabrManifest?
)

object YouTubeStreamResolver {
    private val videoIdPattern = Regex("(?:embed/|watch\\?v=|youtu\\.be/)([A-Za-z0-9_-]{11})")
    private val latinAmericanSpanishRegions = setOf(
        "419", "AR", "BO", "CL", "CO", "CR", "CU", "DO", "EC", "SV", "GT", "HN",
        "MX", "NI", "PA", "PE", "PR", "PY", "US", "UY", "VE"
    )

    @OptIn(UnstableApi::class)
    suspend fun resolve(videoUrl: String): ResolvedYouTubeStream = withContext(Dispatchers.IO) {
        val id = videoIdPattern.find(videoUrl)?.groupValues?.get(1)
            ?: error("No pude identificar el video de YouTube.")
        val info = StreamInfo.getInfo("https://www.youtube.com/watch?v=$id")
        val spanishAudio = info.audioStreams
            .filter { stream -> isSpanish(stream.audioLocale?.toLanguageTag()) }
            .maxByOrNull { stream ->
                val locale = stream.audioLocale
                val latinBonus = if (locale != null && isLatinAmericanSpanish(locale.toLanguageTag())) 1_000_000 else 0
                latinBonus + stream.averageBitrate
            }
        val spanishSubtitle = info.subtitles
            .filter { subtitle -> isSpanish(subtitle.languageTag) }
            .maxByOrNull { subtitle -> if (subtitle.isAutoGenerated) 0 else 1 }
        if (spanishAudio == null && spanishSubtitle == null) {
            error("No encontré audio ni subtítulos identificados como español para esta película.")
        }
        val audio = spanishAudio ?: info.audioStreams.maxByOrNull { it.averageBitrate }
            ?: error("No encontré una pista de audio reproducible para esta película.")
        val video = info.videoOnlyStreams
            .filter { it.height in 1..1080 && it.content.isNotBlank() }
            .maxByOrNull { it.height }
            ?: error("No encontré un flujo de video compatible para esta película.")

        ResolvedYouTubeStream(
            videoUrl = video.content,
            audioUrl = audio.content,
            audioLanguage = audio.audioLocale?.toLanguageTag().orEmpty(),
            hasSpanishAudio = spanishAudio != null,
            spanishSubtitleUrl = spanishSubtitle?.content,
            spanishSubtitleMimeType = spanishSubtitle?.format?.mimeType,
            videoHeight = video.height,
            durationSeconds = info.duration,
            sabrManifest = info.serverAbrStreamingUrl?.takeIf { it.isNotBlank() }
                ?.let { serverAbrUrl ->
                    val sabrAudio = info.audioStreams.map { stream -> stream.toSabrPipedStream() }
                    val sabrVideo = info.videoOnlyStreams.map { stream -> stream.toSabrPipedStream() }
                    if (info.ustreamerConfig.isNullOrBlank() || sabrAudio.isEmpty() || sabrVideo.isEmpty()) null
                    else SabrManifest(
                        id,
                        Streams(
                            duration = info.duration,
                            audioStreams = sabrAudio,
                            videoStreams = sabrVideo,
                            serverAbrStreamingUrl = serverAbrUrl,
                            videoPlaybackUstreamerConfig = info.ustreamerConfig
                        )
                    )
                }
        )
    }

    internal fun isSpanish(languageTag: String?): Boolean {
        if (languageTag.isNullOrBlank()) return false
        return Locale.forLanguageTag(languageTag).language.equals("es", ignoreCase = true)
    }

    internal fun isLatinAmericanSpanish(languageTag: String?): Boolean {
        if (!isSpanish(languageTag)) return false
        val locale = Locale.forLanguageTag(languageTag!!)
        return locale.country.uppercase(Locale.ROOT) in latinAmericanSpanishRegions
    }
}


private fun VideoStream.toSabrPipedStream() = PipedStream(
    codec = codec,
    mimeType = format?.mimeType,
    bitrate = bitrate,
    width = width,
    height = height,
    fps = fps,
    durationMs = itagItem?.approxDurationMs,
    itag = itagItem?.id,
    lastModified = itagItem?.lastModified,
    xtags = itagItem?.xtags
)

private fun AudioStream.toSabrPipedStream() = PipedStream(
    codec = codec,
    mimeType = format?.mimeType,
    bitrate = bitrate,
    durationMs = itagItem?.approxDurationMs,
    audioTrackId = audioTrackId,
    audioTrackType = audioTrackType?.name,
    audioTrackLocale = audioLocale?.toLanguageTag(),
    itag = itagItem?.id,
    lastModified = itagItem?.lastModified,
    isDrc = itagItem?.isDrc,
    xtags = itagItem?.xtags
)
